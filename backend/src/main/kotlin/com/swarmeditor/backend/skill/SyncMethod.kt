package com.swarmeditor.backend.skill

/**
 * Skills 同步策略。
 *
 * 描述 Skills 目录同步到工作区时的行为方式。
 */
enum class SyncMethod {
    /**
     * 自动模式。
     *
     * 优先尝试使用符号链接（Symlink），如果平台不支持（如 Windows 无管理员权限）
     * 或创建失败，则自动回退到物理拷贝（Copy）。
     *
     * 推荐作为默认选项，兼顾实时性与兼容性。
     */
    Auto,

    /**
     * 符号链接模式。
     *
     * 使用文件系统符号链接实现 Skills 目录同步。源文件更新时即时生效，
     * 不占用额外磁盘空间，效率最高。
     *
     * 注意：部分平台（如 Windows 未开启开发者模式）可能需要管理员权限。
     */
    Symlink,

    /**
     * 物理拷贝模式。
     *
     * 将 Skills 目录完整拷贝到目标位置，文件完全独立。
     *
     * 兼容性最好，不受平台限制，但源文件更新后需要重新同步。
     */
    Copy
}
